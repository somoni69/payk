const locales = ['ru', 'tj'];

String tr(String locale, String key, [Map<String, String> vars = const {}]) {
  final pack = locale == 'tj' ? _tj : _ru;
  var text = pack[key] ?? _ru[key] ?? key;
  for (final entry in vars.entries) {
    text = text.replaceAll('{${entry.key}}', entry.value);
  }
  return text;
}

String tierLabel(String locale, int level, {int tiers = 5}) {
  final mapped = tiers <= 4 && level >= 4 ? 5 : level;
  final safe = mapped < 1 ? 1 : (mapped > 5 ? 5 : mapped);
  return tr(locale, 'tier.$safe');
}

